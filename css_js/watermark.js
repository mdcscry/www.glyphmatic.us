function getScript(c) {
    if (c === 8462) return 'math210E';
    if (c === 8463) return 'math210F';
    if (c === 3758 || c === 3773) return 'lao';
    if (c === 3600) return 'thai';
    if (c >= 65136 && c <= 65279) return 'arabic';
    if (c >= 65280 && c <= 65519) return 'fullwidth';
    if (c >= 1024 && c <= 1279) return 'cyrillic';
    if (c >= 880 && c <= 1023 || c >= 7936 && c <= 8191) return 'greek';
    if (c >= 592 && c <= 687) return 'ipa';
    return 'latin';
}

function buildGlyphmaticWatermark() {
    let r = '';
    for (let c of 'glyphmatic.us') {
        const v = LA[c.charCodeAt(0)];
        if (!v || v.length <= 1) { 
            r += `<span data-codes="${c}">${c}</span>`; 
            continue; 
        }
        
        const vc = v[1 + Math.floor(Math.random() * (v.length - 1))];
        const b = String.fromCharCode(vc);
        
        if (noStack.includes(vc)) { 
            r += `<span data-codes="${vc}">${b}</span>`; 
            continue; 
        }
        
        const cf = CF[getScript(vc)];
        if (!cf || !cf.length) { 
            r += `<span data-codes="${vc}">${b}</span>`; 
            continue; 
        }
        
        const n = (getScript(vc).startsWith('math')) ? 1 : (1 + Math.floor(Math.random() * 3));
        let st = b;
        let codes = [vc];
        for (let i = 0; i < n; i++) {
            const cfc = cf[Math.floor(Math.random() * cf.length)];
            st += String.fromCharCode(cfc);
            codes.push(cfc);
        }
        r += `<span data-codes="${codes.join('+')}">${st}</span>`;
    }
    return r;
}

