const noStack = [0x251,0x261,0x210f];

function getScript(c) {
    if (c === 0x210e) return 'math210E';
    if (c === 0x210f) return 'math210F';
    if (c >= 0x1d400 && c <= 0x1d7ff) return 'mathematical';
    if (c === 0xeae || c === 0xebd) return 'lao';
    if (c === 0xe10) return 'thai';
    if ((c >= 0xfe70 && c <= 0xfeff) || (c >= 0x600 && c <= 0x6ff)) return 'arabic';
    if (c >= 0xff00 && c <= 0xff5f) return 'fullwidth';
    if (c >= 0x400 && c <= 0x4ff) return 'cyrillic';
    if (c >= 0x370 && c <= 0x3ff || c >= 0x1f00 && c <= 0x1fff) return 'greek';
    if (c >= 0x250 && c <= 0x2af) return 'ipa';
    if (c >= 0x1780 && c <= 0x17cf) return 'khmer';
    if (c >= 0x531 && c <= 0x58f) return 'armenian';   
    return 'latin';
}

function buildGlyphmaticWatermark() {
    let r = '';
    for (let c of 'glyphmatic.us') {
        const v = LA[c.charCodeAt(0)];
        if (!v || v.length <= 1) { 
            r += `<span data-codes="${c}">${c}</span>`; 
            continue; 
        }
        
        const vc = v[1 + Math.floor(Math.random() * (v.length - 1))];
        const b = String.fromCodePoint(vc);
        
        if (noStack.includes(vc)) { 
            r += `<span data-codes="${vc.toString(16).toUpperCase()}">${b}</span>`; 
            continue; 
        }
        
        const cf = CF[getScript(vc)];
        if (!cf || !cf.length) { 
            r += `<span data-codes="${vc.toString(16).toUpperCase()}">${b}</span>`; 
            continue; 
        }
        
        const script = getScript(vc);
        const n = (script === 'math' || script === 'khmer' || script === 'armenian') ? 1 : (1 + Math.floor(Math.random() * 3));
        let st = b;
        let codes = [vc];
        for (let i = 0; i < n; i++) {
            const cfc = cf[Math.floor(Math.random() * cf.length)];
            st += String.fromCodePoint(cfc);
            codes.push(cfc);
        }
        r += `<span data-codes="${codes.map(c => c.toString(16).toUpperCase()).join('+')}">${st}</span>`;
    }
    return r;
}

